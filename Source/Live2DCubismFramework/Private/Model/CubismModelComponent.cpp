void UCubismModelComponent::AddParameter(const FString ParameterId)
{
	const int32 ParameterIndex = GetParameterCount() + NonNativeParameterIds.Num();

	ParameterIndices.Add(ParameterId, ParameterIndex);
	NonNativeParameterIds.Add(ParameterIndex, ParameterId);
	NonNativeParameterValues.Add(ParameterIndex, 0.0f);

	const FName ComponentName = MakeUniqueObjectName(this, UCubismParameterComponent::StaticClass(), FName(*ParameterId));
	UCubismParameterComponent* Parameter = NewObject<UCubismParameterComponent>(this, ComponentName, RF_Transactional);

	Parameter->Index = ParameterIndex;

	if (GetWorld())
	{
		Parameter->RegisterComponent();
	}

	Parameter->Setup(this);

	// Keep the array dense: the index of a parameter is its position in the array.
	if (Parameters.Num() <= ParameterIndex)
	{
		Parameters.SetNum(ParameterIndex + 1);
	}
	Parameters[ParameterIndex] = Parameter;
}

