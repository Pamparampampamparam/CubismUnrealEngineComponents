void UCubismModelComponent::ComponentSetup()
{
	if (!RawModel || !CanCreateComponents())
	{
		return;
	}

	AActor* Owner = GetOwner();

	// The order of creation matters because the components register tick dependencies on each other in Setup.
	{
		const bool bCreated = !IsValid(ParameterStore);
		UCubismParameterStoreComponent* Component = CreateHelperComponent(ParameterStore, TEXT("CubismParameterStore"));

		if (bCreated)
		{
			Component->RegisterComponent();
			if (Owner)
			{
				Owner->AddInstanceComponent(Component);
			}
		}
	}

	{
		const bool bCreated = !IsValid(Motion);
		UCubismMotionComponent* Component = CreateHelperComponent(Motion, TEXT("CubismMotion"));

		if (MotionJsons.Num() > 0 && Component->Jsons != MotionJsons)
		{
			Component->Jsons = MotionJsons;
		}

		if (bCreated)
		{
			Component->RegisterComponent();
			if (Owner)
			{
				Owner->AddInstanceComponent(Component);
			}
		}
	}

	{
		const bool bCreated = !IsValid(Pose);
		UCubismPoseComponent* Component = CreateHelperComponent(Pose, TEXT("CubismPose"));

		const bool bJsonChanged = PoseJson && Component->Json != PoseJson;

		if (bJsonChanged)
		{
			Component->Json = PoseJson;
		}

		if (bCreated)
		{
			Component->RegisterComponent();
			if (Owner)
			{
				Owner->AddInstanceComponent(Component);
			}
		}
		else if (bJsonChanged)
		{
			Component->Setup(this);
		}
	}

	{
		const bool bCreated = !IsValid(Expression);
		UCubismExpressionComponent* Component = CreateHelperComponent(Expression, TEXT("CubismExpression"));

		if (ExpressionJsons.Num() > 0 && Component->Jsons != ExpressionJsons)
		{
			Component->Jsons = ExpressionJsons;
		}

		if (bCreated)
		{
			Component->RegisterComponent();
			if (Owner)
			{
				Owner->AddInstanceComponent(Component);
			}
		}
	}

	{
		const bool bCreated = !IsValid(Physics);
		UCubismPhysicsComponent* Component = CreateHelperComponent(Physics, TEXT("CubismPhysics"));

		const bool bJsonChanged = PhysicsJson && Component->Json != PhysicsJson;

		if (bJsonChanged)
		{
			Component->Json = PhysicsJson;
		}

		if (bCreated)
		{
			Component->RegisterComponent();
			if (Owner)
			{
				Owner->AddInstanceComponent(Component);
			}
		}
		else if (bJsonChanged)
		{
			Component->Setup(this);
		}
	}

	{
		const bool bCreated = !IsValid(Renderer);
		UCubismRendererComponent* Component = CreateHelperComponent(Renderer, TEXT("CubismRenderer"));

		if (bCreated)
		{
			Component->RegisterComponent();
			if (Owner)
			{
				Owner->AddInstanceComponent(Component);
			}
		}
	}

	SetVisibility(bRenderInWorldSpace, true);
	if (GetOwner() && !GetOwner()->FindComponentByClass<UCubismUpdateControllerComponent>())
	{
		UCubismUpdateControllerComponent* Controller = NewObject<UCubismUpdateControllerComponent>(GetOwner(), UCubismUpdateControllerComponent::StaticClass(), TEXT("CubismUpdateController"));
		Controller->RegisterComponent();
		GetOwner()->AddInstanceComponent(Controller);
	}
}

void UCubismModelComponent::ComponentCleanup(const bool bDestroyHelperComponents)
{
	AActor* Owner = GetOwner();

	// The renderer caches the drawables in its junctions; they are about to be destroyed.
	if (IsValid(Renderer))
	{
		Renderer->Junctions.Empty();
		Renderer->NumMasks = 0;
	}

	for (const TObjectPtr<UCubismDrawableComponent>& Drawable : Drawables)
	{
		if (!IsValid(Drawable))
		{
			continue;
		}

		Drawable->DetachFromComponent(FDetachmentTransformRules::KeepRelativeTransform);
		if (Owner)
		{
			Owner->RemoveInstanceComponent(Drawable);
		}
		Drawable->DestroyComponent();
	}

	for (const TObjectPtr<UCubismParameterComponent>& Parameter : Parameters)
	{
		if (!IsValid(Parameter))
		{
			continue;
		}

		if (Owner)
		{
			Owner->RemoveInstanceComponent(Parameter);
		}
		Parameter->DestroyComponent();
	}

	for (const TObjectPtr<UCubismPartComponent>& Part : Parts)
	{
		if (!IsValid(Part))
		{
			continue;
		}

		if (Owner)
		{
			Owner->RemoveInstanceComponent(Part);
		}
		Part->DestroyComponent();
	}

	Drawables.Empty();
	Parameters.Empty();
	Parts.Empty();

	DrawableIndices.Empty();
	ParameterIndices.Empty();
	PartIndices.Empty();

	NonNativeParameterIds.Empty();
	NonNativeParameterValues.Empty();
	NonNativePartIds.Empty();
	NonNativePartOpacities.Empty();

	if (bDestroyHelperComponents)
	{
		// Only destroy the components this model created (their outer is the model). Components the user added to the actor are left alone.
		TArray<UActorComponent*> HelperComponents;
		HelperComponents.Add(Renderer);
		HelperComponents.Add(ParameterStore);
		HelperComponents.Add(Motion);
		HelperComponents.Add(Expression);
		HelperComponents.Add(Physics);
		HelperComponents.Add(Pose);
		HelperComponents.Add(EyeBlink);
		HelperComponents.Add(HarmonicMotion);
		HelperComponents.Add(LipSync);
		HelperComponents.Add(LookAt);

		for (UActorComponent* Component : HelperComponents)
		{
			if (!IsValid(Component) || Component->GetOuter() != this)
			{
				continue;
			}

			if (Owner)
			{
				Owner->RemoveInstanceComponent(Component);
			}
			Component->DestroyComponent();
		}

		Renderer = nullptr;
		ParameterStore = nullptr;
		Motion = nullptr;
		Expression = nullptr;
		Physics = nullptr;
		Pose = nullptr;
		EyeBlink = nullptr;
		HarmonicMotion = nullptr;
		LipSync = nullptr;
		LookAt = nullptr;
	}
}

void UCubismModelComponent::OnComponentDestroyed(bool bDestroyingHierarchy)
{
	ComponentCleanup(true);

	ReleaseRawModel();

	Super::OnComponentDestroyed(bDestroyingHierarchy);
}

