void UCubismModelComponent::SetParameterValue(const int32 ParameterIndex, const float Value)
{
	if (float* NonNativeValue = NonNativeParameterValues.Find(ParameterIndex))
	{
		*NonNativeValue = Value;
		return;
	}

	if (!RawModel || ParameterIndex < 0 || ParameterIndex >= GetParameterCount())
	{
		return;
	}

	float ValueToSet = Value;
	if (UCubismParameterComponent* P = GetParameter(ParameterIndex))
	{
		ValueToSet = P->IsRepeat()
			? P->GetParameterRepeatValue(Value)
			: P->GetParameterClampValue(Value);
		P->Value = ValueToSet;
	}

	csmGetParameterValues(RawModel)[ParameterIndex] = ValueToSet;
}

