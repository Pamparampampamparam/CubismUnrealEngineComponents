int32 UCubismModelComponent::GetParameterIndex(const FString ParameterId)
{
	if (ParameterId.IsEmpty())
	{
		return -1;
	}

	if (const int32* FoundIndex = ParameterIndices.Find(ParameterId))
	{
		return *FoundIndex;
	}

	// Parameters that are not part of the model are created on demand (e.g. for pose parts and motion curves).
	if (!RawModel)
	{
		return -1;
	}

	AddParameter(ParameterId);

	return ParameterIndices[ParameterId];
}

